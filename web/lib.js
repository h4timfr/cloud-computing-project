  /* A small, honest health summary for the top bar and the Alerts page. Counts only what the
   * API reports: cities answering, how old the newest weather observation is, and whether the
   * last poll worked. No infrastructure detail, no ARNs, no regions. */
  function systemHealth(payload, incidents, nowMs) {
    var zones = (payload && payload.zones) || [];
    var reporting = liveCount(zones);
    var total = toNumber(payload && payload.zone_count);
    var totalCount = total === null ? zones.length : total;
    var feed = payload ? feedStatus(payload, nowMs, 0) : null;
    var stale = (payload && payload.stale_zone_ids) || [];
    var split = alertsSplit({ incidents: incidents || [] });
    var lines = [];
    lines.push({
      icon: reporting >= totalCount && totalCount > 0 ? 'check' : 'warning',
      tone: reporting >= totalCount && totalCount > 0 ? 'ok' : 'watch',
      label: reporting + ' of ' + totalCount + ' ' + zoneNounPlural(payload) + ' reporting'
    });
    if (feed && feed.live && feed.enabled) {
      var age = toNumber(feed.feedAgeSeconds);
      lines.push({
        icon: 'clock',
        tone: feed.state === 'stale' ? 'watch' : 'ok',
        label: age === null ? 'Weather data fresh' : 'Weather updated ' + ageLabel(age)
      });
    } else {
      lines.push({ icon: 'info', tone: 'quiet', label: 'Weather feed not in use for this fleet' });
    }
    if (stale.length) {
      lines.push({
        icon: 'warning', tone: 'watch',
        label: stale.length + (stale.length === 1 ? ' ' + zoneNoun(payload) + ' is' : ' ' + zoneNounPlural(payload) + ' are') + ' not reporting'
      });
    }
    lines.push({
      icon: 'bell',
      tone: split.active.length ? 'watch' : 'ok',
      label: split.active.length
        ? split.active.length + (split.active.length === 1 ? ' active alert' : ' active alerts')
        : 'No active alerts'
    });
    var tone = 'ok';
    lines.forEach(function (line) {
      if (line.tone === 'watch' && tone === 'ok') tone = 'watch';
      if (line.tone === 'bad') tone = 'bad';
    });
    return {
      tone: tone,
      label: tone === 'ok' ? 'Healthy' : (tone === 'bad' ? 'Degraded' : 'Attention'),
      reporting: reporting,
      total: totalCount,
      stale: stale,
      activeAlerts: split.active.length,
      lines: lines
    };
  }

