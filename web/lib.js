  /* Where one reading sits against its own configured threshold. Used for the tile caption
   * and the state colour: never for the score, which always comes from the API. */
  function metricState(zone, metric) {
    var latest = zone && zone.latest;
    var value = toNumber(latest && latest.readings ? latest.readings[metric] : null);
    var limits = (zone && zone.thresholds ? zone.thresholds[metric] : null) || {};
    var watch = toNumber(limits.watch);
    var critical = toNumber(limits.critical);
    var state = 'unknown';
    if (value !== null && critical !== null && value >= critical) state = 'critical';
    else if (value !== null && watch !== null && value >= watch) state = 'watch';
    else if (value !== null) state = 'normal';
    return { metric: metric, value: value, watch: watch, critical: critical, state: state };
  }

  function metricStateCaption(zone, metric) {
    var meta = METRIC_META[metric] || { label: String(metric || ''), unit: '' };
    var state = metricState(zone, metric);
    if (state.value === null) return 'No reading yet';
    if (state.state === 'critical') {
      return 'At or above the ' + formatMetric(metric, state.critical) + ' flooding level';
    }
    if (state.state === 'watch') {
      return 'Above the ' + formatMetric(metric, state.watch) + ' watch level';
    }
    if (state.state === 'unknown') return 'No configured limit for this reading';
    return 'Below the ' + formatMetric(metric, state.watch) + ' watch level';
  }

  /* One plain sentence explaining *why* the city is in its band, plus one line of advice.
   *
   * The sentence answers the two questions a visitor actually has: which measurement is pushing
   * the score up, and which ones are not. Both halves come from the API's own contribution
   * entries - the named driver is the one the API listed first, and a measurement is only called
   * quiet when its own value and its own watch threshold say so. Nothing is assumed about the
   * channels that are not driving risk, and no formula, weight or variable name appears here:
   * those live in the collapsed technical section and on the methodology page.
   *
   *   "Risk is currently WATCH. Soil saturation is the main contributor, while rainfall, drain
   *    level and flow rate remain below their watch levels. Conditions are holding steady."
   */
  function reasonSentence(zone) {
    var latest = zone && zone.latest;
    if (!latest) return '';
    var text = 'Risk is currently ' + classLabel(latest.risk_class) + '.';
    var drivers = (latest.top_drivers || []).filter(function (driver) { return !!driver; });
    var lead = drivers.length ? drivers[0] : null;
    if (!lead) return text;
    text += ' ' + driverLabel(lead) + ' is the main contributor';
    var contributions = contributionMap(zone);
    var quiet = [];
    var alsoUp = [];
    METRIC_ORDER.forEach(function (metric) {
      if (metric === lead) return;
      var entry = contributions[metric];
      if (!entry) return;
      var value = toNumber(entry.value);
      var watch = toNumber(entry.watch_threshold);
      if (value === null || watch === null) return;
      if (value < watch) quiet.push(metricPlain(metric).noun);
      else alsoUp.push(driverLabel(metric));
    });
    if (quiet.length) {
      text += ', while ' + labelList(quiet) +
        (quiet.length === 1 ? ' remains below its watch level' : ' remain below their watch levels');
    }
    if (alsoUp.length) {
      text += (quiet.length ? ', and ' : ', while ') + labelList(alsoUp) + ' is also above its watch level';
    }
    text += '.';

    // trendLabel() formats the delta ("+0.40 m / 5 min"); trendDirection() is the one that
    // answers "which way is this going". Comparing the label to 'rising'/'falling' never
    // matched, so neither sentence could ever appear on a flash-flood board. The numbers stay
    // in the technical table: this sentence is the plain-language one.
    var direction = trendDirection(latest.trend);
    if (direction === 'up') text += ' Conditions are getting worse.';
    else if (direction === 'down') text += ' Conditions are easing.';
    else if (trendHasHistory(latest.trend)) text += ' Conditions are holding steady.';
    return text;
  }

  function plainRiskSummary(zone) {
    var latest = zone && zone.latest;
    var band = classLabel(latest ? latest.risk_class : null);
    var meaning = BAND_MEANING[band] || BAND_MEANING.UNKNOWN;
    var noun = String((zone && zone.name) || 'This site');
    var summary = {
      band: band,
      tone: meaning.tone,
      headline: noun + ': ' + meaning.headline.toLowerCase(),
      short: meaning.headline.charAt(0).toUpperCase() + meaning.headline.slice(1).toLowerCase(),
      advice: meaning.advice,
      why: '',
      driver: null,
      driverLabel: ''
    };
    if (!latest) return summary;

    var drivers = latest.top_drivers || [];
    var driver = drivers.length ? drivers[0] : null;
    summary.driver = driver;
    if (driver) summary.driverLabel = driverLabel(driver);
    // One composer for the plain sentence, so the hero, the city card and the city page cannot
    // drift into three different explanations of the same reading.
    summary.why = reasonSentence(zone);
    return summary;
  }

  /* "5 min ago" from an ISO timestamp the API reported. ageLabel already speaks in
   * relative terms, so nothing is appended to it twice. */
  function relativeTime(isoTimestamp, nowMs) {
    var ms = Date.parse(String(isoTimestamp || ''));
    if (isNaN(ms)) return 'unknown';
    var now = toNumber(nowMs);
    var seconds = Math.max(0, ((now === null ? Date.now() : now) - ms) / 1000);
    var label = ageLabel(seconds);
    if (label === 'just now') return 'just now';
    if (label === 'no data') return 'unknown';
    return label;
  }

  /* ---------------------------------------------------------- routing --- */

  /* '#/cities/city-chennai' -> {view:'city', zoneId:'city-chennai'}, anything unknown ->
   * the default view. Kept tiny and total: the router can never throw on a bad URL, including
   * a fragment that is not valid percent-encoding ('#/cities/%'), where decodeURIComponent
   * throws a URIError that would otherwise abort start() and leave the page never polling. */
  function routeFromHash(hash) {
    var raw = String(hash === null || hash === undefined ? '' : hash).replace(/^#\/?/, '');
    var parts = raw.split('/').filter(function (part) { return part.length > 0; });
    var view = parts.length ? parts[0].toLowerCase() : DEFAULT_VIEW;
    // a city lives inside the cities section: #/cities/<zone_id>
    if ((view === 'city' || view === 'cities') && parts[1]) {
      return { view: 'city', zoneId: safeDecode(parts[1]) };
    }
    if (view === 'city') return { view: 'cities', zoneId: null };
    var known = NAV_ITEMS.map(function (item) { return item.view; });
    if (known.indexOf(view) < 0) return { view: DEFAULT_VIEW, zoneId: null };
    return { view: view, zoneId: null };
  }

  /* Percent-decode a URL fragment, tolerating a malformed one: the raw text is a better
   * answer than an exception, and the zone id is only ever used as an opaque key. */
  function safeDecode(value) {
    try {
      return decodeURIComponent(value);
    } catch (error) {
      return String(value);
    }
  }

  function hashFor(view, zoneId) {
    if (view === 'city' && zoneId) return '#/cities/' + encodeURIComponent(zoneId);
    var known = NAV_ITEMS.filter(function (item) { return item.view === view; });
    return known.length ? known[0].hash : NAV_ITEMS[0].hash;
  }

