  /* A one-sentence, plain-language reason for an incident, assembled only from fields the API
   * actually reports - no invented cause, no claim about what a human decided. */
  function alertReason(incident) {
    if (!incident || typeof incident !== 'object') return '';
    var severity = classLabel(incident.severity_at_open || incident.severity);
    var driver = incident.top_driver_label || metricPlain(incident.top_driver).noun;
    var score = formatScore(incident.risk_score_at_open);
    var sentence = 'Opened when the risk score reached ' + severity + ' at ' + score + '.';
    if (driver && driver !== 'not recorded') {
      sentence += ' The measurement contributing most was ' + driver + '.';
    }
    if (incident.simulated === true) {
      sentence += ' Every value behind this incident was simulated.';
    } else if (incident.data_classification === 'mixed') {
      sentence += ' This incident mixes measured and simulated values.';
    }
    return sentence;
  }

